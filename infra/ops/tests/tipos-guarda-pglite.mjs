// infra/ops/tests/tipos-guarda-pglite.mjs — SDD-0586: corre en PGlite (un PostgreSQL real, en proceso) la consulta del
// catálogo de la guarda de tipos de infra/ops/portal-historial/ensayo-portal.sh, tal como la arma tipos_sql. La usa
// prueba-portal-historial.sh. Los dobles de psql no ejecutan SQL, y así se coló un `order by 1 collate "C"` que
// Postgres rechaza (revisión del DG de la #563, B2).
//
// Uso:  node tipos-guarda-pglite.mjs <consulta.sql>
// Imprime `filas=<n> ausentes=<n> orden_c=<si|no>` y sale con 0; si Postgres rechaza la consulta, `error=<mensaje>` y 3.
import { readFileSync } from "node:fs";
import { PGlite } from "@electric-sql/pglite";

const q = readFileSync(process.argv[2], "utf8").trim();
const db = new PGlite();
// Tablas de la lista con tipos conocidos. chatwoot_webhook_events trae event y event_key, que ordenan distinto en C y en
// en_US (B1).
await db.exec(`
  create table public.tenants (id uuid primary key);
  create table public.crm_historial_etapas (id bigint generated by default as identity primary key, tenant_id uuid not null);
  create table public.chatwoot_webhook_events (tenant_id uuid, event_key text, event text, conversation_id bigint, status text, received_at timestamptz);
`);
try {
  const filas = (await db.query(q, [], { rowMode: "array" })).rows.map((r) => r[0]);
  const enC = [...filas].sort((a, b) => Buffer.compare(Buffer.from(a), Buffer.from(b)));
  const conocidas = filas.filter((f) => /^public\.(tenants|crm_historial_etapas|chatwoot_webhook_events)\./.test(f));
  console.log(
    `filas=${filas.length} ausentes=${filas.filter((f) => f.endsWith(":ausente")).length} ` +
      `orden_c=${JSON.stringify(enC) === JSON.stringify(filas) ? "si" : "no"}`,
  );
  for (const f of conocidas) console.log(`tipo ${f}`);
} catch (e) {
  console.log(`error=${String(e.message).replace(/\s+/g, "_")}`);
  process.exitCode = 3;
}
await db.close();
