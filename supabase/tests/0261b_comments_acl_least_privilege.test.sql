\set ON_ERROR_STOP on

-- Prueba contractual autocontenida de 0261b. Simula el ACL amplio que
-- Supabase dejó en las tablas históricas, ejecuta la corrección dos veces
-- para probar idempotencia y termina siempre con ROLLBACK.
begin;

do $fixture_guard$
begin
  if to_regclass('public.comments') is not null
     or to_regclass('public.comment_mentions') is not null
     or to_regclass('public.comment_reactions') is not null then
    raise exception 'Fixture 0261b rechazada: los objetos reales ya existen';
  end if;

  if not exists (select 1 from pg_roles where rolname = 'anon') then
    create role anon nologin;
  end if;

  if not exists (select 1 from pg_roles where rolname = 'authenticated') then
    create role authenticated nologin;
  end if;

  if not exists (select 1 from pg_roles where rolname = 'service_role') then
    create role service_role nologin;
  end if;
end
$fixture_guard$;

create table public.comments (
  id bigint generated by default as identity primary key,
  body text not null
);

create table public.comment_mentions (
  id bigint generated by default as identity primary key,
  comment_id bigint not null references public.comments(id)
);

create table public.comment_reactions (
  id bigint generated by default as identity primary key,
  comment_id bigint not null references public.comments(id)
);

alter table public.comments enable row level security;
alter table public.comment_mentions enable row level security;
alter table public.comment_reactions enable row level security;

grant all privileges
  on table public.comments, public.comment_mentions, public.comment_reactions
  to anon, authenticated, service_role;

create temporary table comments_acl_service_role_before as
select
  c.oid as table_oid,
  array_agg(
    acl.privilege_type || ':' || acl.is_grantable::text
    order by acl.privilege_type, acl.is_grantable
  ) as privileges
from pg_class as c
cross join lateral aclexplode(
  coalesce(c.relacl, acldefault('r', c.relowner))
) as acl
join pg_roles as grantee
  on grantee.oid = acl.grantee
where c.oid in (
  'public.comments'::regclass,
  'public.comment_mentions'::regclass,
  'public.comment_reactions'::regclass
)
  and grantee.rolname = 'service_role'
group by c.oid;

\ir ../migrations/0261b_comments_acl_least_privilege.sql
\ir ../migrations/0261b_comments_acl_least_privilege.sql

do $assertions$
declare
  v_contract record;
  v_actual text[];
  v_anon_count integer;
  v_public_count integer;
  v_grant_option_count integer;
  v_service_before text[];
  v_service_after text[];
begin
  for v_contract in
    select *
    from (
      values
        (
          'public.comments'::text,
          array['INSERT', 'SELECT', 'UPDATE']::text[]
        ),
        (
          'public.comment_mentions'::text,
          array['INSERT', 'SELECT', 'UPDATE']::text[]
        ),
        (
          'public.comment_reactions'::text,
          array['DELETE', 'INSERT', 'SELECT']::text[]
        )
    ) as expected(table_name, privileges)
  loop
    select coalesce(
      array_agg(acl.privilege_type order by acl.privilege_type),
      array[]::text[]
    )
      into v_actual
    from pg_class as c
    cross join lateral aclexplode(
      coalesce(c.relacl, acldefault('r', c.relowner))
    ) as acl
    join pg_roles as grantee
      on grantee.oid = acl.grantee
    where c.oid = to_regclass(v_contract.table_name)
      and grantee.rolname = 'authenticated';

    if v_actual is distinct from v_contract.privileges then
      raise exception
        'TEST 0261b: ACL authenticated inesperado en %: esperado %, actual %',
        v_contract.table_name, v_contract.privileges, v_actual;
    end if;

    select count(*)
      into v_grant_option_count
    from pg_class as c
    cross join lateral aclexplode(
      coalesce(c.relacl, acldefault('r', c.relowner))
    ) as acl
    join pg_roles as grantee
      on grantee.oid = acl.grantee
    where c.oid = to_regclass(v_contract.table_name)
      and grantee.rolname = 'authenticated'
      and acl.is_grantable;

    if v_grant_option_count <> 0 then
      raise exception
        'TEST 0261b: authenticated conserva WITH GRANT OPTION en %',
        v_contract.table_name;
    end if;

    select count(*)
      into v_anon_count
    from pg_class as c
    cross join lateral aclexplode(
      coalesce(c.relacl, acldefault('r', c.relowner))
    ) as acl
    join pg_roles as grantee
      on grantee.oid = acl.grantee
    where c.oid = to_regclass(v_contract.table_name)
      and grantee.rolname = 'anon';

    if v_anon_count <> 0 then
      raise exception
        'TEST 0261b: anon conserva % privilegios directos en %',
        v_anon_count, v_contract.table_name;
    end if;

    select count(*)
      into v_public_count
    from pg_class as c
    cross join lateral aclexplode(
      coalesce(c.relacl, acldefault('r', c.relowner))
    ) as acl
    where c.oid = to_regclass(v_contract.table_name)
      and acl.grantee = 0;

    if v_public_count <> 0 then
      raise exception
        'TEST 0261b: PUBLIC conserva % privilegios en %',
        v_public_count, v_contract.table_name;
    end if;

    select privileges
      into v_service_before
    from comments_acl_service_role_before
    where table_oid = to_regclass(v_contract.table_name);

    select array_agg(
      acl.privilege_type || ':' || acl.is_grantable::text
      order by acl.privilege_type, acl.is_grantable
    )
      into v_service_after
    from pg_class as c
    cross join lateral aclexplode(
      coalesce(c.relacl, acldefault('r', c.relowner))
    ) as acl
    join pg_roles as grantee
      on grantee.oid = acl.grantee
    where c.oid = to_regclass(v_contract.table_name)
      and grantee.rolname = 'service_role';

    if v_service_after is distinct from v_service_before then
      raise exception
        'TEST 0261b: cambió el ACL de service_role en %',
        v_contract.table_name;
    end if;
  end loop;

  if exists (
    select 1
    from pg_class
    where oid in (
      'public.comments'::regclass,
      'public.comment_mentions'::regclass,
      'public.comment_reactions'::regclass
    )
      and not relrowsecurity
  ) then
    raise exception 'TEST 0261b: la corrección desactivó RLS';
  end if;
end
$assertions$;

rollback;

select
  to_regclass('public.comments') is null
  and to_regclass('public.comment_mentions') is null
  and to_regclass('public.comment_reactions') is null
  as comments_acl_fixture_rolled_back;
